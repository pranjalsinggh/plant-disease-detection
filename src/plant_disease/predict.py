"""Load a trained checkpoint and classify a leaf photograph."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Sequence

import torch
from PIL import Image

from .artifacts import load_checkpoint, resolve_device
from .model import PlantDiseaseCNN
from .transforms import ImageTransform


class Predictor:
    """Inference wrapper with the checkpoint's class order and preprocessing."""

    def __init__(
        self,
        model: PlantDiseaseCNN,
        classes: list[str],
        image_size: int,
        device: torch.device,
        metadata: dict[str, Any],
    ) -> None:
        self.model = model.eval()
        self.classes = list(classes)
        self.image_size = image_size
        self.device = device
        self.metadata = metadata
        self.transform = ImageTransform(image_size=image_size)

    def predict(self, image: Image.Image, top_k: int = 3) -> list[dict[str, str | float]]:
        if isinstance(top_k, bool) or not isinstance(top_k, int) or top_k < 1:
            raise ValueError("top_k must be a positive integer.")
        tensor = self.transform(image).unsqueeze(0).to(self.device)
        with torch.inference_mode():
            logits = self.model(tensor)
            if logits.shape != (1, len(self.classes)) or not torch.isfinite(logits).all():
                raise ValueError("Checkpoint produced invalid scores. Retrain or use a valid best.pt checkpoint.")
            probabilities = torch.softmax(logits, dim=1)[0]
            values, positions = probabilities.topk(min(top_k, len(self.classes)))
        return [
            {"label": self.classes[position], "probability": probability}
            for probability, position in zip(values.cpu().tolist(), positions.cpu().tolist())
        ]


def load_predictor(checkpoint: str | Path, device: str = "cpu") -> Predictor:
    payload = load_checkpoint(checkpoint)
    target_device = resolve_device(device)
    dropout = payload["config"].get("dropout", 0.4)
    if isinstance(dropout, bool) or not isinstance(dropout, (int, float)):
        raise ValueError("Checkpoint dropout must be a numeric training setting.")
    model = PlantDiseaseCNN(num_classes=len(payload["classes"]), dropout=dropout)
    try:
        model.load_state_dict(payload["model_state"], strict=True)
    except (RuntimeError, TypeError) as exc:
        raise ValueError(
            "Checkpoint weights do not match the four-layer CNN or class count. "
            "Use best.pt generated by this project's training command."
        ) from exc
    model.to(target_device).eval()
    with torch.inference_mode():
        scores = model(torch.zeros(1, 3, payload["image_size"], payload["image_size"], device=target_device))
        if scores.shape != (1, len(payload["classes"])) or not torch.isfinite(scores).all():
            raise ValueError("Checkpoint input size or weights produce invalid model outputs.")
    return Predictor(model, payload["classes"], payload["image_size"], target_device, payload)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--checkpoint", required=True, help="A trained best.pt checkpoint")
    parser.add_argument("--image", required=True, help="Path to a leaf image")
    parser.add_argument("--top-k", type=int, default=3, help="Number of highest-probability labels")
    parser.add_argument("--device", default="cpu", help="cpu, cuda, or auto")
    args = parser.parse_args(argv)
    try:
        predictor = load_predictor(args.checkpoint, args.device)
        with Image.open(args.image) as image:
            results = predictor.predict(image, args.top_k)
    except (OSError, ValueError, RuntimeError) as exc:
        parser.exit(2, f"Prediction error: {exc}\n")
    payload = {
        "image": str(Path(args.image)),
        "predictions": results,
        "synthetic_checkpoint": bool(predictor.metadata.get("synthetic_images", False)),
        "score_context": "Softmax model scores are not calibrated confidence estimates.",
    }
    if payload["synthetic_checkpoint"]:
        payload["warning"] = "Synthetic-image smoke checkpoint; predictions do not establish plant disease detection."
    print(json.dumps(payload, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

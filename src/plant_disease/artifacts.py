"""Checkpoint validation and durable experiment artifacts."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import torch

from .transforms import validate_image_size


def write_json(path: str | Path, payload: dict[str, Any]) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(payload, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    temporary.replace(path)


def prepare_output(output_dir: str | Path, overwrite: bool = False) -> Path:
    """Refuse a populated run directory unless the user explicitly opts in."""
    output = Path(output_dir).expanduser().resolve()
    if output.exists() and not output.is_dir():
        raise ValueError(f"Output path is a file, not a directory: {output}")
    if output.exists() and any(output.iterdir()) and not overwrite:
        raise FileExistsError(
            f"Output directory contains files: {output}. Choose a new run directory "
            "or pass --overwrite to replace this run's artifacts."
        )
    output.mkdir(parents=True, exist_ok=True)
    return output


def save_checkpoint(path: str | Path, checkpoint: dict[str, Any]) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    torch.save(checkpoint, temporary)
    temporary.replace(path)


def load_checkpoint(path: str | Path) -> dict[str, Any]:
    """Load tensor/primitive-only checkpoints without executing pickle code."""
    path = Path(path).expanduser()
    if not path.is_file():
        raise FileNotFoundError(
            f"No trained checkpoint found at {path}. Train first with "
            "python -m plant_disease.train --index data/index.sqlite "
            "--config configs/train.json --output artifacts/run."
        )
    try:
        checkpoint = torch.load(path, map_location="cpu", weights_only=True)
    except Exception as exc:
        raise ValueError(
            f"Could not read checkpoint {path}. Use best.pt generated by this project's "
            "training command; unsafe pickle loading is disabled."
        ) from exc
    if not isinstance(checkpoint, dict):
        raise ValueError("Checkpoint must be a dictionary of model weights and metadata.")
    required = {"model_state", "classes", "image_size", "epoch", "metrics", "config"}
    missing = required - checkpoint.keys()
    if missing:
        raise ValueError(f"Checkpoint is missing metadata: {', '.join(sorted(missing))}.")
    if checkpoint.get("format_version", 1) != 1:
        raise ValueError("Unsupported checkpoint format version; retrain with this project.")
    if checkpoint.get("architecture", "four_layer_cnn") != "four_layer_cnn":
        raise ValueError("Checkpoint architecture must be four_layer_cnn.")
    classes = checkpoint["classes"]
    if (
        not isinstance(classes, list)
        or len(classes) < 2
        or not all(isinstance(label, str) and label.strip() for label in classes)
        or len(set(classes)) != len(classes)
    ):
        raise ValueError("Checkpoint classes must contain at least two unique, non-empty names.")
    validate_image_size(checkpoint["image_size"])
    epoch = checkpoint["epoch"]
    if isinstance(epoch, bool) or not isinstance(epoch, int) or epoch < 1:
        raise ValueError("Checkpoint epoch must be a positive integer.")
    if not isinstance(checkpoint["config"], dict) or not isinstance(checkpoint["metrics"], dict):
        raise ValueError("Checkpoint config and metrics must be dictionaries.")
    if checkpoint["config"].get("image_size", checkpoint["image_size"]) != checkpoint["image_size"]:
        raise ValueError("Checkpoint input size does not match its training configuration.")
    state = checkpoint["model_state"]
    if not isinstance(state, dict) or not state or not all(
        isinstance(name, str) and isinstance(value, torch.Tensor) for name, value in state.items()
    ):
        raise ValueError("Checkpoint model_state must contain named weight tensors.")
    return checkpoint


def resolve_device(name: str = "auto") -> torch.device:
    if name == "auto":
        name = "cuda" if torch.cuda.is_available() else "cpu"
    try:
        device = torch.device(name)
    except (RuntimeError, ValueError) as exc:
        raise ValueError("Invalid device. Use cpu, cuda, or auto.") from exc
    if device.type not in {"cpu", "cuda"}:
        raise ValueError("Supported devices are cpu and cuda (or auto for automatic selection).")
    if device.type == "cuda":
        if not torch.cuda.is_available():
            raise ValueError("CUDA is unavailable. Choose --device cpu or install CUDA-enabled PyTorch.")
        if device.index is not None and device.index >= torch.cuda.device_count():
            raise ValueError(f"CUDA device {device.index} is unavailable.")
    return device
